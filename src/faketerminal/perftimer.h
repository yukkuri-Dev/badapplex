#ifndef FAKETERMINAL_PERFTIMER_H
#define FAKETERMINAL_PERFTIMER_H

#include <stdint.h>

// TMU(タイマユニット)のチャネル1をフリーランのダウンカウンタとして使う、
// 計測専用の軽量タイマー。play中のフレームあたりの処理時間を実機上で
// 直接比べるためのもの(DMA/backbuf方式 vs VRAM直接方式、等)。
//
// チャネル0はRAMTEST等の他機能で将来使われる可能性があるため触らず、
// チャネル1を計測専用に固定して使う。

// タイマーを初期化して自由走行を開始する(1回だけ呼べばよい)。
void perftimer_init(void);

// 現在のティックカウント(単調増加)を返す。分周比はTIMER_CLK_4固定。
// 絶対的な秒数への換算はペリフェラルクロックが不明なため行わない。
// 同じビルド・同じ実行内でのティック差分を比較する用途に限る。
//
// 機種をまたいだ比較には使えない: DATAPLUS6とDATAPLUS7でavg_ticksを
// 比較したところ約2倍の差が出たが、実際の総再生時間の差は数%程度
// (220秒の動画で8〜16秒)しかなかった。TMUの前提クロック(ペリフェラル
// クロック)自体が機種間で異なるため、ティック数の「刻み幅」が違い、
// 絶対値はおろか比率での比較すら成立しない。機種が違う場合は
// avg_ticksではなくストップウォッチ等での実測時間で比較すること。
uint32_t perftimer_ticks(void);

#endif /* FAKETERMINAL_PERFTIMER_H */
